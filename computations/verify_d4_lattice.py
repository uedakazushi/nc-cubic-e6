"""Exact intersection lattice for a cubic surface with anticanonical triangle.

Blow-up marking: Pic = Z H + sum Z E_i, intersection H^2=1,
E_i^2=-1, H.E_i=0. D_i=H-E_(2i-1)-E_(2i).
The integer solution to L.D_i=0 is generated by four roots below.
"""
import json
from pathlib import Path
import sympy as s
Q=s.diag(1,*([-1]*6))
H=s.Matrix([1,0,0,0,0,0,0])
Es=[s.eye(7)[:,i] for i in range(1,7)]
D=[H-Es[0]-Es[1], H-Es[2]-Es[3], H-Es[4]-Es[5]]
roots=[H-Es[0]-Es[2]-Es[4],Es[0]-Es[1],Es[2]-Es[3],Es[4]-Es[5]]
M=s.Matrix.hstack(*roots)
J=s.Matrix([[int(v.dot(Q*w)) for w in roots] for v in roots])
expected=s.Matrix([[-2,1,1,1],[1,-2,0,0],[1,0,-2,0],[1,0,0,-2]])
assert J==expected and J.det()==4
assert all((v.T*Q*d)[0]==0 for v in roots for d in D)
assert sum(D,s.zeros(7,1))==3*H-sum(Es,s.zeros(7,1))
assert s.Matrix.hstack(*D).rank()==3 and M.rank()==4
# Explicit parameterization of all integral orthogonal lattice vectors:
# L=a H - sum_i b_i E_i with b1+b2=b3+b4=b5+b6=a.
# In terms of our positive E_i-coordinate vectors, each basis vector
# is a root above and the coefficient of central root is a.
# Thus there is no finite-index gap.
